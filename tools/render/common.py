"""Shared helpers for the pre-rendered faces (tools/render/<face>.py): supersampled numpy canvases,
bloom for light that glows on the AMOLED, RGB565 dithering, glyph strips for text drawn on the watch,
and writing the images to web/img/<KEY>/, web/js/img/<face>.js (data URIs + metrics) and
watch/source/gen/Img<Face>.mc (the same metrics for Monkey C)."""
import base64
import math
import os

import numpy as np
from PIL import Image, ImageDraw, ImageFilter, ImageFont

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
SS = 3
N = 454
C = 227.0
rng = np.random.default_rng(970)

DIN = "/System/Library/Fonts/Supplemental/DIN Condensed Bold.ttf"
DINA = "/System/Library/Fonts/Supplemental/DIN Alternate Bold.ttf"
AVENIR = "/System/Library/Fonts/Avenir Next.ttc"  # index 0 Bold, 5 Medium, 7 Regular, 10 Ultra Light
DIDOT = "/System/Library/Fonts/Supplemental/Didot.ttc"


def grid(w=N, h=N):
    y, x = np.mgrid[0:h * SS, 0:w * SS].astype(np.float32)
    return (x + 0.5) / SS, (y + 0.5) / SS


def smooth(a, b, v):
    t = np.clip((v - a) / (b - a), 0, 1)
    return t * t * (3 - 2 * t)


def polar(x, y, cx=C, cy=C):
    dx, dy = x - cx, y - cy
    return np.sqrt(dx * dx + dy * dy), np.arctan2(dx, -dy)  # 0 = 12 o'clock, clockwise


def down(a):
    """float HxWxC (0..1), supersampled -> PIL image at 1/SS."""
    b = np.clip(a * 255 + 0.5, 0, 255).astype(np.uint8)
    im = Image.fromarray(b, {1: "L", 3: "RGB", 4: "RGBA"}[b.shape[2]] if b.ndim == 3 else "L")
    return im.resize((im.width // SS, im.height // SS), Image.LANCZOS)


def dither565(im, amp=1.0):
    a = np.asarray(im).astype(np.float32)
    n = rng.uniform(-1, 1, a.shape[:2] + (1,)).astype(np.float32)
    a[..., :3] = a[..., :3] + n * np.array([4.0, 2.0, 4.0], np.float32) * amp
    return Image.fromarray(np.clip(a + 0.5, 0, 255).astype(np.uint8), im.mode)


def bloom(core, radii=((5, 0.55), (16, 0.35))):
    """core: float HxW (supersampled, 0..1) -> core plus soft halos (light bleeding on glass)."""
    out = core.copy()
    im = Image.fromarray(np.clip(core * 255, 0, 255).astype(np.uint8))
    for r, k in radii:
        b = np.asarray(im.filter(ImageFilter.GaussianBlur(r * SS))).astype(np.float32) / 255
        out = out + b * k
    return np.clip(out, 0, 1)


def mask_draw(w, h, fn):
    """Draw white shapes with PIL at supersampled size -> float mask (h*SS, w*SS)."""
    im = Image.new("L", (w * SS, h * SS), 0)
    fn(ImageDraw.Draw(im), SS)
    return np.asarray(im).astype(np.float32) / 255


def font(path, px, idx=0):
    return ImageFont.truetype(path, int(px * SS), index=idx)


def glyph_strip(chars, path, px, cell_h, idx=0, color=(255, 255, 255), glow=None, pad=2):
    """One horizontal strip of glyphs (white on transparent) + per-glyph advance widths (px).
    Cells are as wide as the widest glyph; the watch draws each glyph through a clip."""
    f = font(path, px, idx)
    tmp = ImageDraw.Draw(Image.new("L", (10, 10)))
    adv = [max(1, int(round(tmp.textlength(ch, font=f) / SS))) for ch in chars]
    cw = max(adv) + 2 * pad
    im = Image.new("L", (cw * len(chars) * SS, cell_h * SS), 0)
    dr = ImageDraw.Draw(im)
    for i, ch in enumerate(chars):
        dr.text(((i * cw + pad) * SS, cell_h * SS / 2), ch, font=f, fill=255, anchor="lm")
    a = np.asarray(im).astype(np.float32) / 255
    if glow:
        a = bloom(a, glow)
    rgba = np.zeros(a.shape + (4,), np.float32)
    rgba[..., 0], rgba[..., 1], rgba[..., 2] = color[0] / 255, color[1] / 255, color[2] / 255
    rgba[..., 3] = a
    return down(rgba), cw, adv


class Out:
    """Collects images and metrics of one face and writes all outputs."""

    def __init__(self, key, mod):
        self.key, self.mod = key, mod  # e.g. "COCKPIT", "cockpit"
        self.dir = os.path.join(ROOT, "web", "img", key)
        os.makedirs(self.dir, exist_ok=True)
        self.files, self.meta = {}, {}

    def save(self, name, im, fmt="png"):
        p = os.path.join(self.dir, name + "." + fmt)
        if fmt == "jpg":
            im.convert("RGB").save(p, quality=93, subsampling=0, optimize=True)
        else:
            im.save(p, optimize=True)
        self.files[name] = (fmt, p)

    def const(self, name, value):
        self.meta[name] = value

    def write(self):
        lines = ["// GENERATED by tools/render/%s.py — do not edit. Pre-rendered images as data URIs + metrics." % self.mod,
                 "export const M = {"]
        for k, v in self.meta.items():
            lines.append("  %s: %s," % (k, v if not isinstance(v, str) else '"%s"' % v))
        lines += ["};", "export default {"]
        for name, (fmt, p) in self.files.items():
            mime = "image/jpeg" if fmt == "jpg" else "image/png"
            lines.append('  %s: "data:%s;base64,%s",' % (name, mime, base64.b64encode(open(p, "rb").read()).decode()))
        lines.append("};")
        os.makedirs(os.path.join(ROOT, "web", "js", "img"), exist_ok=True)
        open(os.path.join(ROOT, "web", "js", "img", self.mod + ".js"), "w").write("\n".join(lines) + "\n")
        if self.meta:
            mc = ["// GENERATED by tools/render/%s.py — do not edit." % self.mod, "import Toybox.Lang;", "",
                  "module Img%s {" % (self.mod[0].upper() + self.mod[1:])]
            for k, v in self.meta.items():
                if isinstance(v, list):
                    mc.append("    const %s = [%s];" % (k, ", ".join(str(x) for x in v)))
                elif isinstance(v, str):
                    mc.append('    const %s = "%s";' % (k, v))
                else:
                    mc.append("    const %s = %s;" % (k, v))
            mc.append("}")
            open(os.path.join(ROOT, "watch", "source", "gen", "Img%s.mc" % (self.mod[0].upper() + self.mod[1:])), "w").write("\n".join(mc) + "\n")
        for name, (fmt, p) in self.files.items():
            im = Image.open(p)
            print("%-10s %4d x %-4d %6d bytes" % (name, im.width, im.height, os.path.getsize(p)))
