#!/usr/bin/env python3
"""FaceLab build: compiles one .prg per watch face design.

Each design becomes its own Connect IQ watch face (own app id, own name) that
contains the shared engine (watch/source/*.mc) plus exactly one design
(watch/source/faces/<Key>.mc). This keeps every face well below the 128 KB
watch face memory limit of the Forerunner 970.

Usage:
  tools/build.py                 # build all faces from web/faces.json
  tools/build.py ALPE MONO       # build selected faces
Options (env):
  CIQ_SDK   path to the Connect IQ SDK      (default /opt/ciq/sdk)
  CIQ_KEY   developer key (.der)            (default tools/keys/facelab-sideload.der)
  CIQ_DEVICE device id                      (default fr970)
  CODE_<KEY> Face-Code to bake in (else the face default)
"""
import hashlib
import json
import os
import shutil
import subprocess
import sys
import zlib
import struct

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SDK = os.environ.get("CIQ_SDK", "/opt/ciq/sdk")
KEY = os.environ.get("CIQ_KEY", os.path.join(ROOT, "tools", "keys", "facelab-sideload.der"))
DEVICE = os.environ.get("CIQ_DEVICE", "fr970")
OUT = os.path.join(ROOT, "dist")
BUILD = os.path.join(ROOT, "build")

CODE_LEN = 120   # placeholder length for the patchable Face-Code
NAME_BYTES = 48  # UTF-8 byte length of the patchable app name (padded with NBSP)

with open(os.path.join(ROOT, "web", "faces.json"), encoding="utf-8") as f:
    META = json.load(f)


def hex6(n):
    return "%06X" % (n & 0xFFFFFF)


def default_code(face):
    d = face["defaults"]
    return ".".join(str(x) for x in [
        "FL1", face["key"], d.get("style", 1), hex6(int(d["accent"], 16)), hex6(int(d["dcol"], 16)),
        "-".join(str(s) for s in d["slots"]), d.get("ftp", 250), d.get("kg", 75), d.get("climb", 0),
        d.get("quest", 1), d.get("anim", 2), d.get("bikeGoal", 150)])


def pad_name(name):
    """Pad the app name with NBSP (2 bytes) / space to exactly NAME_BYTES so the studio can patch it."""
    n = len(name.encode("utf-8"))
    if n > NAME_BYTES:
        raise ValueError("name too long: " + name)
    rest = NAME_BYTES - n
    return name + (" " if rest % 2 else "") + "\u00a0" * (rest // 2)


def app_id(key):
    return hashlib.md5(("facelab-" + key).encode()).hexdigest()


def png(path, size, accent):
    """Launcher icon: accent ring on black."""
    w = h = size
    r0, r1 = size * 0.30, size * 0.44
    ar, ag, ab = (accent >> 16) & 255, (accent >> 8) & 255, accent & 255
    rows = []
    for y in range(h):
        row = bytearray([0])
        for x in range(w):
            dx, dy = x - w / 2 + 0.5, y - h / 2 + 0.5
            dist = (dx * dx + dy * dy) ** 0.5
            if r0 <= dist <= r1:
                row += bytes([ar, ag, ab, 255])
            elif dist < r0 * 0.45:
                row += bytes([255, 255, 255, 255])
            else:
                row += bytes([0, 0, 0, 0])
        rows.append(bytes(row))
    raw = b"".join(rows)

    def ch(t, d):
        return struct.pack(">I", len(d)) + t + d + struct.pack(">I", zlib.crc32(t + d) & 0xFFFFFFFF)
    data = b"\x89PNG\r\n\x1a\n" + ch(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 6, 0, 0, 0)) + ch(b"IDAT", zlib.compress(raw)) + ch(b"IEND", b"")
    with open(path, "wb") as f:
        f.write(data)


def xml_escape(s):
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("'", "&apos;").replace('"', "&quot;")


def stage(face):
    key = face["key"]
    d = os.path.join(BUILD, key)
    if os.path.exists(d):
        shutil.rmtree(d)
    src = os.path.join(d, "source")
    res = os.path.join(d, "resources")
    os.makedirs(os.path.join(src, "gen"))
    os.makedirs(os.path.join(res, "drawables"))
    os.makedirs(os.path.join(res, "strings"))
    os.makedirs(os.path.join(res, "configs"))
    wsrc = os.path.join(ROOT, "watch", "source")
    for fn in os.listdir(wsrc):
        if fn.endswith(".mc"):
            shutil.copy(os.path.join(wsrc, fn), src)
    shutil.copy(os.path.join(wsrc, "gen", "FontData.mc"), os.path.join(src, "gen"))
    shutil.copy(os.path.join(wsrc, "faces", face["file"]), src)

    styles = face.get("styles", ["Standard"])
    uses = face.get("uses", [])
    menu = ["style"] if len(styles) > 1 else []
    menu += ["anim"] + [u for u in uses if u in ("ftp", "kg", "climb", "quest", "bike")]
    with open(os.path.join(src, "gen", "Registry.mc"), "w", encoding="utf-8") as f:
        f.write("// GENERATED by tools/build.py\nimport Toybox.Lang;\n\nmodule Registry {\n")
        f.write('    const KEY = "%s";\n' % key)
        f.write('    const DEBUG = %s;\n' % ("true" if os.environ.get("FL_DEBUG") else "false"))
        f.write("    const STYLES = [%s];\n" % ", ".join('"%s"' % s for s in styles))
        f.write("    const USES = [%s];\n" % ", ".join('"%s"' % u for u in menu))
        f.write("    function make() as Face {\n        return new %s();\n    }\n}\n" % face["cls"])

    code = os.environ.get("CODE_" + key) or default_code(face)
    placeholder = ("FLCODE:" + code).ljust(CODE_LEN, "#")
    with open(os.path.join(res, "strings", "strings.xml"), "w", encoding="utf-8") as f:
        f.write("<strings>\n")
        f.write('  <string id="AppName">%s</string>\n' % xml_escape(pad_name(face["name"])))
        f.write('  <string id="FaceCode">%s</string>\n' % xml_escape(placeholder))
        for i, s in enumerate(styles):
            f.write('  <string id="style%d">%s</string>\n' % (i + 1, xml_escape(s)))
        f.write("</strings>\n")
    with open(os.path.join(res, "drawables", "drawables.xml"), "w") as f:
        f.write('<drawables>\n  <bitmap id="LauncherIcon" filename="icon.png"/>\n</drawables>\n')
    png(os.path.join(res, "drawables", "icon.png"), 65, int(face["defaults"]["accent"], 16))

    dstyle = face["defaults"].get("style", 1)
    slots = face["defaults"]["slots"]
    with open(os.path.join(res, "configs", "watchface.xml"), "w") as f:
        f.write("<resources>\n  <watchface-config>\n    <styles>\n")
        for i in range(len(styles)):
            f.write('      <style id="%d" label="@Strings.style%d"%s/>\n' % (i + 1, i + 1, ' default="true"' if i + 1 == dstyle else ""))
        f.write("    </styles>\n    <accentColors allowAny=\"true\"/>\n    <data>\n")
        if "slots" in uses:
            for i in range(3):
                f.write('      <complication id="%d" allowAny="true"/>\n' % (i + 1))
        f.write("    </data>\n  </watchface-config>\n</resources>\n")

    perms = ["ComplicationSubscriber", "SensorHistory", "UserProfile"]
    with open(os.path.join(d, "manifest.xml"), "w") as f:
        f.write('<?xml version="1.0"?>\n<iq:manifest xmlns:iq="http://www.garmin.com/xml/connectiq" version="3">\n')
        f.write('  <iq:application entry="FaceLabApp" id="%s" launcherIcon="@Drawables.LauncherIcon" minApiLevel="5.1.0" name="@Strings.AppName" type="watchface" version="1.0.0">\n' % app_id(key))
        f.write('    <iq:products>\n      <iq:product id="%s"/>\n    </iq:products>\n' % DEVICE)
        f.write("    <iq:permissions>\n%s    </iq:permissions>\n" % "".join('      <iq:uses-permission id="%s"/>\n' % p for p in perms))
        f.write("    <iq:languages>\n      <iq:language>deu</iq:language>\n      <iq:language>eng</iq:language>\n    </iq:languages>\n    <iq:barrels/>\n  </iq:application>\n</iq:manifest>\n")
    with open(os.path.join(d, "monkey.jungle"), "w") as f:
        f.write("project.manifest = manifest.xml\n")
    return d


def ensure_key():
    """Create a local developer key on first use (never committed, see .gitignore)."""
    if os.path.exists(KEY):
        return
    os.makedirs(os.path.dirname(KEY), exist_ok=True)
    pem = KEY + ".pem"
    subprocess.run(["openssl", "genrsa", "-out", pem, "4096"], check=True, capture_output=True)
    subprocess.run(["openssl", "pkcs8", "-topk8", "-inform", "PEM", "-outform", "DER", "-in", pem, "-out", KEY, "-nocrypt"],
                   check=True, capture_output=True)
    os.remove(pem)
    print("created developer key", KEY)


def compile_face(face, typecheck="2"):
    d = stage(face)
    os.makedirs(OUT, exist_ok=True)
    # compile into the face's own build dir: the compiler writes intermediates (gen/, mir/)
    # next to the output, so parallel builds must not share an output folder
    tmp = os.path.join(d, "out", face["key"] + ".prg")
    os.makedirs(os.path.dirname(tmp), exist_ok=True)
    out = os.path.join(OUT, face["key"] + ".prg")
    cmd = ["java", "-Xms1g", "-Xss128m", "-Dfile.encoding=UTF-8", "-jar", os.path.join(SDK, "bin", "monkeybrains.jar"),
           "-o", tmp, "-f", os.path.join(d, "monkey.jungle"), "-y", KEY, "-d", DEVICE, "-w", "-l", typecheck, "-O", "2"]
    if os.environ.get("CIQ_RELEASE"):
        cmd.append("-r")
    p = subprocess.run(cmd, capture_output=True, text=True)
    log = "\n".join(l for l in (p.stdout + p.stderr).splitlines() if "JAVA_TOOL_OPTIONS" not in l)
    ok = p.returncode == 0 and os.path.exists(tmp)
    if ok:
        shutil.copy(tmp, out + ".part")
        os.replace(out + ".part", out)
    return ok, out, log


def main():
    keys = sys.argv[1:]
    faces = [f for f in META["faces"] if not keys or f["key"] in keys]
    if keys and len(faces) != len(keys):
        print("unknown face key(s):", set(keys) - {f["key"] for f in faces})
        sys.exit(2)
    ensure_key()
    failed = 0
    for face in faces:
        ok, out, log = compile_face(face, os.environ.get("CIQ_TYPECHECK", "1"))
        print(("OK   " if ok else "FAIL ") + face["key"] + ("  " + str(os.path.getsize(out)) + " bytes" if ok else ""))
        quiet = [l for l in log.splitlines() if l.strip() and "BUILD SUCCESSFUL" not in l and "launcher icon" not in l
                 and (os.environ.get("VERBOSE") or "WARNING" not in l)]
        if quiet:
            print("\n".join("     " + l for l in quiet[:40]))
        failed += 0 if ok else 1
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()
