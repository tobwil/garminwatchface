// Generates web/js/faces/index.js (static imports of every face listed in web/faces.json
// whose JS file exists) so the studio can be bundled into a single file.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const meta = JSON.parse(readFileSync(join(ROOT, "web/faces.json"), "utf8"));
const present = meta.faces.filter((f) => existsSync(join(ROOT, "web/js/faces", f.js)));
const lines = ["// GENERATED by tools/gen-registry.mjs — do not edit."];
present.forEach((f, i) => lines.push(`import f${i} from "./${f.js}";`));
lines.push("export const FACES = {");
present.forEach((f, i) => lines.push(`  ${f.key}: f${i},`));
lines.push("};", "");
writeFileSync(join(ROOT, "web/js/faces/index.js"), lines.join("\n"));
console.log("registry:", present.map((f) => f.key).join(" "));
