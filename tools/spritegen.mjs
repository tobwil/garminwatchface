// Generates Monkey C sprite constants from web/js/sprites/<name>.js.
// Each module default-exports { SPRITE_NAME: { w, h, rows: [...] }, ... }.
// Output: watch/source/gen/Spr<Name>.mc with `module Spr<Name> { const SPRITE_NAME = [...]b; }`
// Faces list the sprite modules they need in web/faces.json ("sprites": ["rider"]).
// Run: node tools/spritegen.mjs
import { readdirSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { encodeSprite } from "../web/js/engine/spr.js";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(ROOT, "web/js/sprites");
for (const f of readdirSync(dir).filter((x) => x.endsWith(".js"))) {
  const name = f.replace(/\.js$/, "");
  const mod = (await import(pathToFileURL(join(dir, f)).href + "?t=" + Date.now())).default;
  const modName = "Spr" + name[0].toUpperCase() + name.slice(1);
  const lines = [`// GENERATED by tools/spritegen.mjs from web/js/sprites/${f} — do not edit.`, "import Toybox.Lang;", "", `module ${modName} {`];
  for (const [k, def] of Object.entries(mod)) {
    if (!/^[A-Z][A-Z0-9_]*$/.test(k)) throw new Error(`${f}: sprite name ${k} must be UPPER_CASE`);
    const b = [...encodeSprite(def)];
    const chunks = [];
    for (let i = 0; i < b.length; i += 32) chunks.push("        " + b.slice(i, i + 32).join(","));
    lines.push(`    const ${k} = [\n${chunks.join(",\n")}\n    ]b;`);
  }
  lines.push("}", "");
  writeFileSync(join(ROOT, "watch/source/gen", modName + ".mc"), lines.join("\n"));
  console.log(modName, Object.keys(mod).length, "sprites");
}
