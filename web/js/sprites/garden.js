// Hedgehog: 1 spines, 2 face, 3 eye / nose / feet. Butterfly: 1 wing, 2 body. Watering can: 1 body, 2 rim.

// a copy of rows with single pixels replaced: marks = [[row, col, "c"], ...]
function mark(rows, marks) {
  const r = rows.slice();
  for (const [y, x, c] of marks) r[y] = r[y].substring(0, x) + c + r[y].substring(x + 1);
  return r;
}

