// Pixel Buddy sprites (face BUDDY). Drawn at 5 px per pixel.
// Body palette: 0 outline, 1 body, 2 highlight, 3 shade/feet, 4 belly, 5 inner ear / cheek.
// The round body frames are generated from one shape description (so squash, stretch and
// lying poses stay consistent); faces, hats and props are hand-drawn.

// ---- body generator: ellipse + two ear nubs + two feet, outlined and shaded
function blob(W, H, o) {
  const cx = (W - 1) / 2;
  const top = o.ear;                 // body starts below the ears
  const bot = H - 1 - o.foot;        // body ends above the feet
  const cy = (top + bot) / 2;
  const rx = W / 2 - 0.35, ry = (bot - top + 1) / 2 - 0.1;
  const inE = (x, y, ex, ey, ax, ay) => ((x - ex) / ax) ** 2 + ((y - ey) / ay) ** 2 <= 1;
  const body = (x, y) => inE(x, y, cx, cy, rx, ry);
  const earY = top - 0.2;
  const ear = (x, y) => o.ear > 0 && y < top + 2 && (inE(x, y, cx - o.ex, earY, 1.75, 2.3) || inE(x, y, cx + o.ex, earY, 1.75, 2.3));
  const feet = (x, y) => o.foot > 0 && y > bot - 1 && (inE(x, y, cx - o.fx, H - 1.6, 2.3, 1.45) || inE(x, y, cx + o.fx, H - 1.6, 2.3, 1.45));
  const m = (x, y) => x >= 0 && y >= 0 && x < W && y < H && (body(x, y) || ear(x, y) || feet(x, y));
  const rows = [];
  for (let y = 0; y < H; y++) {
    let r = "";
    for (let x = 0; x < W; x++) {
      if (!m(x, y)) { r += "."; continue; }
      if (!m(x - 1, y) || !m(x + 1, y) || !m(x, y - 1) || !m(x, y + 1)) { r += "0"; continue; }
      if (!body(x, y) && feet(x, y)) { r += "3"; continue; }
      if (!body(x, y) && ear(x, y)) { r += "5"; continue; }
      if (inE(x, y, cx - rx * 0.5, cy - ry * 0.5, rx * 0.17, ry * 0.12)) { r += "2"; continue; }
      if (!inE(x, y, cx - rx * 0.2, cy - ry * 0.24, rx * 1.0, ry * 1.04)) { r += "3"; continue; }
      if (inE(x, y, cx, cy + ry * 0.52, rx * 0.4, ry * 0.32)) { r += "4"; continue; }
      r += "1";
    }
    rows.push(r);
  }
  return { w: W, h: H, rows };
}

