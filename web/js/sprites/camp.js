// a ridge tent seen from the front, the door open on the right half
function tent() {
  const rows = [];
  for (let r = 0; r < 13; r++) {
    let s = "";
    for (let c = 0; c < 24; c++) {
      const dx = c - 11.5;
      if (r === 0) s += c === 11 || c === 12 ? "4" : ".";
      else if (Math.abs(dx) > r * 0.95 + 0.5) s += ".";
      else if (r >= 4 && dx > -0.5 && dx < (r - 3) * 0.5) s += "3";
      else s += dx < 0 ? "1" : "2";
    }
    rows.push(s);
  }
  return rows;
}

